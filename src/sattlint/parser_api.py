"""Single import door for ``sattline-parser``.

SattLint reads the parser through this module only. Everything the analyzers,
resolution, validation, and project layers need is re-exported here, so a parser
release that moves its internal modules cannot break imports scattered across the
tree.

The module re-exports, it does not wrap. There is no behavior here: the names are the
parser's own objects, and the AST surface below is the parser's public ``ast`` module.

Do not import ``sattline_parser`` submodules anywhere else in ``src/``. ``tests/`` may
reach for the parser directly, because the contract tests exist to pin that surface.

Two doors beyond the documented set are deliberate. ``sattline_parser.api`` holds
the custom-parser builder and the CP1252 reader, and ``sattline_parser.builtins``
holds the builtin function signatures and record specs; the parser publishes no
other door for them.
"""

